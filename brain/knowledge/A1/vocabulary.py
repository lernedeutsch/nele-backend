# ==========================================
# HOTELWORTSCHATZ VORBEREITEN
# ==========================================

def prepare_vocabulary(
    source
):

    prepared = {}

    for word, data in source.items():

        entry = dict(
            data
        )

        examples = entry.get(
            "examples"
        )

        if (
            examples
            and isinstance(
                examples,
                list
            )
        ):

            entry["example"] = (
                f"Beispiel: „{examples[0]}“"
            )

        prepared[
            word
        ] = entry

    return prepared


